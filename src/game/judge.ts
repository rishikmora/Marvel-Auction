import type { AuctionAnalytics } from './analytics';
import { seededRandom } from './rng';
import type { Character, RankedTeam } from './types';

/**
 * The Judge.
 *
 * The auction's official champion is decided by a published formula anyone can audit.
 * The Judge is a *second opinion* on the same rosters, weighing things the formula
 * deliberately does not: how top-heavy a squad is, whether it has a true heavyweight,
 * whether it reads as a coherent team, and how well it was bought.
 *
 * It is allowed to disagree. When the power gap is wide it won't; when the auction was
 * close, the lens matters and that is where the argument lives.
 */

export interface JudgeCriterion {
  id: string;
  label: string;
  /** What this lens is measuring, in one line. */
  description: string;
  weight: number;
  /** 0-1 per team, keyed by playerId. */
  scores: Record<string, number>;
}

export interface JudgeTeamNote {
  playerId: string;
  teamName: string;
  /** 0-100 composite under the Judge's weighting. */
  score: number;
  rank: number;
  strengths: string[];
  weaknesses: string[];
}

export interface JudgeVerdict {
  /** Who the Judge would crown. */
  winnerPlayerId: string | null;
  winnerTeamName: string | null;
  /** 0-1. Low means the Judge thinks it was genuinely close. */
  confidence: number;
  headline: string;
  /** The argument, in order. */
  reasoning: string[];
  teams: JudgeTeamNote[];
  criteria: JudgeCriterion[];
  /** Set when the Judge disagrees with the power-score champion. */
  dissent: string | null;
  /** 'local' when generated by this engine, 'claude' when written by the model. */
  source: 'local' | 'claude';
  model?: string;
}

const clamp01 = (value: number) => Math.max(0, Math.min(1, value));

/** Scales a set of raw values to 0-1 against the best performer in the field. */
function normalize(values: Record<string, number>): Record<string, number> {
  const entries = Object.entries(values);
  if (!entries.length) return {};
  const max = Math.max(...entries.map(([, value]) => value));
  const min = Math.min(...entries.map(([, value]) => value));
  const span = max - min;
  return Object.fromEntries(
    entries.map(([key, value]) => [key, span <= 0 ? 1 : clamp01((value - min) / span)]),
  );
}

/** Gini-style evenness: 1 means every pick is equally strong, 0 means one carry. */
function depthScore(powers: number[]): number {
  if (powers.length < 2) return 0.5;
  const mean = powers.reduce((sum, value) => sum + value, 0) / powers.length;
  if (mean <= 0) return 0;
  const variance =
    powers.reduce((sum, value) => sum + (value - mean) ** 2, 0) / powers.length;
  const cv = Math.sqrt(variance) / mean;
  // A coefficient of variation above ~0.45 is a very top-heavy roster.
  return clamp01(1 - cv / 0.45);
}

/** How strongly a roster reads as one team rather than seven strangers. */
function identityScore(characters: Character[]): { score: number; theme: string | null } {
  if (characters.length < 2) return { score: 0.4, theme: null };
  const counts = new Map<string, number>();
  for (const character of characters) {
    for (const tag of character.synergyTags) {
      counts.set(tag, (counts.get(tag) ?? 0) + 1);
    }
  }
  let bestTag: string | null = null;
  let bestCount = 0;
  for (const [tag, count] of counts) {
    if (count > bestCount) {
      bestCount = count;
      bestTag = tag;
    }
  }
  const share = bestCount / characters.length;
  return { score: clamp01((share - 0.25) / 0.6), theme: bestCount >= 3 ? bestTag : null };
}

export interface JudgeInput {
  rankings: RankedTeam[];
  characters: Map<string, Character>;
  analytics: AuctionAnalytics;
  /** Keeps phrasing stable for a given game. */
  seed: string;
}

/**
 * Builds the verdict from the finished rosters.
 *
 * Pure and deterministic: the same game always produces the same verdict, so two players
 * reading it separately see the same argument.
 */
export function judgeAuction({
  rankings,
  characters,
  analytics,
  seed,
}: JudgeInput): JudgeVerdict {
  const random = seededRandom(`judge:${seed}`);

  if (!rankings.length) {
    return {
      winnerPlayerId: null,
      winnerTeamName: null,
      confidence: 0,
      headline: 'No rosters to judge.',
      reasoning: ['Nobody finished the auction with a team, so there is nothing to weigh.'],
      teams: [],
      criteria: [],
      dissent: null,
      source: 'local',
    };
  }

  const rosterOf = (team: RankedTeam): Character[] =>
    team.characters
      .map((entry) => characters.get(entry.characterId))
      .filter((character): character is Character => Boolean(character));

  /* ---------------------------- raw measures ---------------------------- */
  const rawPower: Record<string, number> = {};
  const rawDepth: Record<string, number> = {};
  const rawStar: Record<string, number> = {};
  const rawIdentity: Record<string, number> = {};
  const rawValue: Record<string, number> = {};
  const themes: Record<string, string | null> = {};

  for (const team of rankings) {
    const roster = rosterOf(team);
    const powers = team.characters.map((entry) => entry.power);
    const analytic = analytics.players.find((entry) => entry.playerId === team.playerId);
    const identity = identityScore(roster);

    rawPower[team.playerId] = team.total;
    rawDepth[team.playerId] = depthScore(powers);
    rawStar[team.playerId] = team.strongestCharacterPower;
    rawIdentity[team.playerId] = identity.score;
    rawValue[team.playerId] = analytic?.powerPerCredit ?? 0;
    themes[team.playerId] = identity.theme;
  }

  /* ------------------------------ criteria ------------------------------ */
  const criteria: JudgeCriterion[] = [
    {
      id: 'power',
      label: 'Raw team power',
      description: 'The published score — character strength plus synergy, balance and leadership.',
      weight: 0.5,
      scores: normalize(rawPower),
    },
    {
      id: 'depth',
      label: 'Depth',
      description: 'How evenly the strength is spread. A single carry is fragile.',
      weight: 0.15,
      scores: normalize(rawDepth),
    },
    {
      id: 'value',
      label: 'Value',
      description: 'Power bought per credit. Smart shopping counts for something.',
      weight: 0.15,
      scores: normalize(rawValue),
    },
    {
      id: 'star',
      label: 'Star power',
      description: 'The single best character on the roster — someone who wins a fight alone.',
      weight: 0.1,
      scores: normalize(rawStar),
    },
    {
      id: 'identity',
      label: 'Identity',
      description: 'Whether the roster reads as one team rather than seven strangers.',
      weight: 0.1,
      scores: normalize(rawIdentity),
    },
  ];

  /* ---------------------------- composite ------------------------------- */
  const composite: Record<string, number> = {};
  for (const team of rankings) {
    let total = 0;
    for (const criterion of criteria) {
      total += (criterion.scores[team.playerId] ?? 0) * criterion.weight;
    }
    // A whisper of variance keeps identical rosters from tying forever, but it is far
    // too small to overturn any real difference.
    composite[team.playerId] = total * 100 + random() * 0.01;
  }

  const ordered = [...rankings].sort(
    (a, b) => composite[b.playerId] - composite[a.playerId],
  );
  const winner = ordered[0];
  const runnerUp = ordered[1];

  const margin = runnerUp
    ? (composite[winner.playerId] - composite[runnerUp.playerId]) /
      Math.max(1, composite[winner.playerId])
    : 1;
  const confidence = clamp01(0.5 + margin * 3.5);

  /* ----------------------------- team notes ----------------------------- */
  const teams: JudgeTeamNote[] = ordered.map((team, index) => {
    const strengths: string[] = [];
    const weaknesses: string[] = [];
    const scoreFor = (id: string) => criteria.find((c) => c.id === id)?.scores[team.playerId] ?? 0;

    if (scoreFor('power') > 0.75) strengths.push('top-end power');
    if (scoreFor('depth') > 0.7) strengths.push('no weak link');
    else if (scoreFor('depth') < 0.35) weaknesses.push('leans hard on one or two names');
    if (scoreFor('value') > 0.75) strengths.push('bought well');
    else if (scoreFor('value') < 0.3) weaknesses.push('overpaid for what it got');
    if (scoreFor('star') > 0.8) strengths.push('a genuine heavyweight');
    else if (scoreFor('star') < 0.3) weaknesses.push('nobody who wins a fight alone');
    if (themes[team.playerId]) strengths.push(`a clear ${themes[team.playerId]} identity`);
    if (team.balance.rolesMissing.length > 2) weaknesses.push('gaps in role coverage');
    if (team.penalty > 0) weaknesses.push('stacked too many of the same role');

    return {
      playerId: team.playerId,
      teamName: team.player.teamName,
      score: Math.round(composite[team.playerId] * 10) / 10,
      rank: index + 1,
      strengths: strengths.length ? strengths : ['a workable roster'],
      weaknesses,
    };
  });

  /* ------------------------------ argument ------------------------------ */
  const officialChampion = rankings.find((team) => team.rank === 1) ?? rankings[0];
  const disagrees = officialChampion.playerId !== winner.playerId;
  const winnerNote = teams[0];

  const reasoning: string[] = [];
  reasoning.push(
    `${winner.player.teamName} takes it on ${winnerNote.strengths.slice(0, 2).join(' and ')}.`,
  );

  const winnerValue = analytics.players.find((entry) => entry.playerId === winner.playerId);
  if (winnerValue && winnerValue.characters > 0) {
    reasoning.push(
      `They committed ${winnerValue.spent} credits for ${winnerValue.totalPower} power — ${winnerValue.powerPerCredit} per credit, ${
        winnerValue.discipline <= 1 ? 'at or under' : 'above'
      } the recommended prices.`,
    );
  }

  if (runnerUp) {
    const runnerNote = teams[1];
    reasoning.push(
      `${runnerUp.player.teamName} pushes them close — ${runnerNote.strengths[0]} — but ${
        runnerNote.weaknesses[0] ?? 'the margin was never quite there'
      }.`,
    );
  }

  if (disagrees) {
    reasoning.push(
      `This is not the published result. On raw score ${officialChampion.player.teamName} finishes ahead by ${
        officialChampion.total - winner.total
      }, but weighing depth, value and star power the call flips.`,
    );
  } else if (confidence > 0.85) {
    reasoning.push('The scoreboard and the eye test agree, and not narrowly.');
  } else {
    reasoning.push('The scoreboard and the eye test agree, though it was closer than the gap suggests.');
  }

  const headline = disagrees
    ? `${winner.player.teamName} should have won it`
    : `${winner.player.teamName} earned it`;

  return {
    winnerPlayerId: winner.playerId,
    winnerTeamName: winner.player.teamName,
    confidence: Math.round(confidence * 100) / 100,
    headline,
    reasoning,
    teams,
    criteria,
    dissent: disagrees
      ? `The Judge picks ${winner.player.teamName}; the power score crowns ${officialChampion.player.teamName}.`
      : null,
    source: 'local',
  };
}
